/**
 * API contract shared by the backend (src/app/api, src/server) and the
 * frontend client (src/lib/api.ts). Types only — no runtime code, no secrets.
 *
 * Every error response has the same shape: { error: { code, message } }.
 */

// ---- Resources -------------------------------------------------------------

/** GET /api/me — the signed-in user. Name/email/image may be missing from Google. */
export type MeDTO = {
  id: string;
  name: string | null;
  email: string | null;
  image: string | null;
  favoriteMovie: string | null;
};

export type FactDTO = { id: string; movie: string; content: string; createdAt: string };

/**
 * fresh    — newly generated by OpenAI and stored
 * cache    — latest fact is < 60s old (or another request just generated it)
 * fallback — OpenAI failed; this is the most recent stored fact
 */
export type FactSource = "fresh" | "cache" | "fallback";

// ---- Endpoint payloads -----------------------------------------------------

/** GET /api/me → 200 */
export type GetMeResponse = { user: MeDTO };

/** PUT /api/me/movie request body */
export type UpdateMovieRequest = { movie: string };
/** PUT /api/me/movie → 200 */
export type UpdateMovieResponse = { user: MeDTO };

/** GET /api/fact → 200 */
export type GetFactResponse = { fact: FactDTO; source: FactSource };

// ---- Errors ----------------------------------------------------------------

export type ApiErrorCode =
  | "UNAUTHORIZED" // 401 — not signed in
  | "VALIDATION_ERROR" // 400 — bad request body
  | "NO_MOVIE" // 409 — onboarding not completed
  | "FACT_UNAVAILABLE" // 503 — OpenAI failed and no stored fact exists
  | "INTERNAL_ERROR"; // 500 — unexpected server error

export type ApiErrorBody = { error: { code: ApiErrorCode; message: string } };
